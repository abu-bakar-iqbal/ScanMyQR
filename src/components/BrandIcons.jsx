export function getPlatformIconComponent(iconName) {
  switch (iconName) {
    case 'MessageCircle':
    case 'WhatsApp':
      return WhatsAppIcon;
    case 'Star':
    case 'GoogleReview':
    case 'google_review':
      return GoogleReviewIcon;
    case 'Instagram':
      return InstagramIcon;
    case 'Facebook':
      return FacebookIcon;
    case 'Linkedin':
      return LinkedInIcon;
    case 'Video':
    case 'TikTok':
      return TikTokIcon;
    case 'Globe':
      return Globe;
    default:
      return LinkIcon;
  }
}
